'''
Important concept: each LCEL component transforms data
You can think of the chain like a data pipeline:

Component               Input                  Output
----------------------------------------------------------------
ChatPromptTemplate      dict                   ChatPromptValue
ChatOpenAI              ChatPromptValue        AIMessage
StrOutputParser         AIMessage              str

This is one of the most important ways to understand LCEL.

Each component:

Receives an input.
Processes/transforms it.
Passes its output to the next component.

'''

from dotenv import load_dotenv
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import StrOutputParser
from langchain_openai import ChatOpenAI

# load env data
load_dotenv()

# Create a prompt 
prompt =ChatPromptTemplate.from_messages(
    [
        ("system",
         "You are a helpful tutor. Explain the concepts in simple way."
        ),
        ("human",
         "Explain {topic} in {number} simple sentences"
        )
    ]
)

# create llm
llm=ChatOpenAI(
    model="gpt-4o-mini",
    temperature=0.1,
    max_completion_tokens=80
)

# Step 3: Create the output parser
output_parser=StrOutputParser()

# create the complete chain
chain=prompt | llm | output_parser

response=chain.invoke(
    {
       "topic":"Explain output parser in langchain" ,
       "number":2
    }
)

#print response
print(f"\nResponse: {response}")

print("\nResponse Type:",type(response))

'''
Response: In LangChain, an output parser is a tool that helps interpret and format 
the results generated by a language model. It takes the raw text output and transforms it into 
a structured format, like JSON or a specific data type, making it easier to use in applications.

Response Type:<class 'langchain_core.messages.base.TextAccessor'>

'''